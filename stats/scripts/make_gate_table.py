"""Build the exploratory-gate lookup table (STATS_LOG R2-6) from the validation results.

Writes trendtrial/gate_table.json and patches the GATE_TABLE block in js/trendtrial.js, so Python and JS ship the same table.
usage: python scripts/make_gate_table.py [--res out/validation/validation_results.json] [--adaptive out/validation/r2_adaptive.json]
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument("--res", default=str(ROOT / "out/validation/validation_results.json"))
ap.add_argument("--adaptive", default=None)
a = ap.parse_args()
res = json.loads(Path(a.res).read_text(encoding="utf-8"))
ad = json.loads(Path(a.adaptive).read_text(encoding="utf-8"))["cells"] if a.adaptive else res["adaptive"]["cells"]
sc = {s["id"]: s for s in res["scenarios"]}
rows = []
for n in (23, 25, 45):
    for phi in (0.0, 0.1, 0.2, 0.3, 0.45, 0.6):
        yw = sc[f"R-null-n{n}-phi{phi}"]["candidates"]["yue_wang"]["size"]
        p = sc[f"R-trend-n{n}-phi{phi}"]["candidates"]["yue_wang"]["power"]
        an = ad[f"n{n}-phi{phi}"]["null"]
        rows.append(dict(n=n, phi=phi, size=round(yw["value"], 4), se=round(yw["se"], 4),
                         passes=bool(yw["value"] <= 0.05 + 2 * yw["se"]), power=round(p["value"], 3),
                         adaptive_size=round(an["reject_unconditional"]["value"], 4),
                         adaptive_release=round(an["release_rate"]["value"], 3),
                         adaptive_size_given_release=round(an["reject_given_release"]["value"], 4)))
table = dict(
    source="synthetic validation, STATS_LOG run B (Yue-Wang size, 4000 series per row) and round 2 (adaptive procedure, seed family 2026)",
    correction="yw", correction_name="Mann-Kendall with Yue-Wang effective-sample-size correction",
    nominal_size=0.05, rows=rows,
    gaps=dict(n=25, phi=0.3, size=round(sc["R-null-gaps-n25-phi0.3"]["candidates"]["yue_wang"]["size"]["value"], 4)),
    skewed=dict(n=25, phi=0.3, size=round(sc["R-null-skewed-n25-phi0.3"]["candidates"]["yue_wang"]["size"]["value"], 4)),
    rules=dict(n_min=20, n_max=50, skew_max=0.8, phi_max=0.6))
Path(ROOT / "trendtrial/gate_table.json").write_text(json.dumps(table, indent=1), encoding="utf-8")
js = ROOT / "js/trendtrial.js"
s = js.read_text(encoding="utf-8")
block = "// BEGIN GATE_TABLE (generated by stats/scripts/make_gate_table.py; do not edit)\nexport const GATE_TABLE = " + \
        json.dumps(table, indent=1) + ";\n// END GATE_TABLE"
if "// BEGIN GATE_TABLE" in s:
    s = re.sub(r"// BEGIN GATE_TABLE.*?// END GATE_TABLE", lambda m: block, s, flags=re.S)
else:
    s = s.replace("// ------------------------------------------------------------------ convenience", block + "\n\n// ------------------------------------------------------------------ convenience", 1)
js.write_text(s, encoding="utf-8")
print("gate table written:", len(rows), "rows")
